const TIER_AR: Record<BadgeTier, string> = { common: "عادية", rare: "نادرة", epic: "ملحمية", legendary: "أسطورية" };
const TIER_EN: Record<BadgeTier, string> = { common: "Common", rare: "Rare", epic: "Epic", legendary: "Legendary" };

export function localizeBadge<T extends Pick<BadgeDef, "key" | "name" | "desc">>(badge: T, locale: Locale): T {
  if (locale !== "ar") return badge;
  const [name, desc] = AR[badge.key] ?? [badge.name, badge.desc];
  return { ...badge, name, desc };
}

export function localizeTier(tier: BadgeTier, locale: Locale): string {
  return locale === "ar" ? TIER_AR[tier] : TIER_EN[tier];
}
